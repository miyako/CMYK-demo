#!/usr/bin/env bash
# Deterministic checks that need no 4D runtime. Run from the repository root.
#
#   1. the form is valid against the 4D form JSON schema (boon)
#   2. the form geometry fits the fixed window and nothing overlaps
#   3. every Form.<name> binding points at a real class property
#   4. project JSON files parse
#
# The runtime checks (dependency install, conversion matrix) live in
# scripts/accept.sh because they need tool4d.
set -euo pipefail

cd "$(dirname "$0")/.."

echo "== boon: form schema"
tools/4dform/boon .agents/schemas/4dform/formsSchema.json Project/Sources/Forms/Lab/form.4DForm

echo "== layout"
python3 scripts/check_layout.py

echo "== bindings"
python3 scripts/check_bindings.py \
  --class Project/Sources/Classes/CMYKLab.4dm \
  --form Project/Sources/Forms/Lab/form.4DForm

echo "== project json"
python3 - <<'PY'
import json, pathlib
paths = [p for p in pathlib.Path("Project").rglob("*") if p.suffix in {".4DProject", ".json"}]
for path in sorted(paths):
    if "DerivedData" in path.parts:
        continue  # generated by the 4D runtime, not tracked
    json.loads(path.read_text(encoding="utf-8"))
    print(f"ok {path}")
PY

echo "all static checks passed"
